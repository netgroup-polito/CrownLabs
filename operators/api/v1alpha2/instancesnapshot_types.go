package v1alpha2

import (
	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
)

// InstanceSnapshotSpec defines the desired state of InstanceSnapshot.
type InstanceSnapshotSpec struct {
	// Instance is the reference to the persistent VM instance to be snapshotted.
	Instance GenericRef `json:"instanceRef"`

	// Environment represents the reference to the environment to be snapshotted.
	Environment GenericRef `json:"environmentRef,omitempty"`

	// ImageName is the name of the image to pushed in the docker registry.
	ImageName string `json:"imageName"`

	// DestinationNamespace is the namespace where the snapshot DataVolume will be created.
	// If empty, defaults to the InstanceSnapshot's own namespace.
	// +optional
	DestinationNamespace string `json:"destinationNamespace,omitempty"`
}

// SnapshotPhase describes the current phase of the InstanceSnapshot.
// +kubebuilder:validation:Enum=Pending;Ready;Failed
type SnapshotPhase string

const (
	// SnapshotPhasePending means the snapshot is being created.
	SnapshotPhasePending SnapshotPhase = "Pending"
	// SnapshotPhaseReady means the snapshot has been successfully created.
	SnapshotPhaseReady SnapshotPhase = "Ready"
	// SnapshotPhaseFailed means the snapshot creation failed.
	SnapshotPhaseFailed SnapshotPhase = "Failed"
)

// SnapshotArtifact describes the final artifact generated by the snapshot.
type SnapshotArtifact struct {
	// DataVolumeRef points to the generated DataVolume.
	// +optional
	DataVolumeRef corev1.ObjectReference `json:"dataVolumeRef,omitempty"`
}

// InstanceSnapshotStatus defines the observed state of InstanceSnapshot.
type InstanceSnapshotStatus struct {
	// Phase is the current phase of the snapshot.
	// +optional
	Phase SnapshotPhase `json:"phase,omitempty"`
	// Artifact contains references to the generated resources.
	// +optional
	Artifact SnapshotArtifact `json:"artifact,omitempty"`
	// Conditions hold the latest available observations of the snapshot state.
	// +optional
	Conditions []metav1.Condition `json:"conditions,omitempty"`
}

// +kubebuilder:object:root=true
// +kubebuilder:subresource:status
// +kubebuilder:resource:shortName="isnap"
// +kubebuilder:printcolumn:name="Phase",type=string,JSONPath=`.status.phase`
// +kubebuilder:printcolumn:name="ImageName",type=string,JSONPath=`.spec.imageName`
// +kubebuilder:printcolumn:name="Age",type=date,JSONPath=`.metadata.creationTimestamp`

// InstanceSnapshot is the Schema for the instancesnapshots API.
type InstanceSnapshot struct {
	metav1.TypeMeta   `json:",inline"`
	metav1.ObjectMeta `json:"metadata,omitempty"`

	Spec   InstanceSnapshotSpec   `json:"spec,omitempty"`
	Status InstanceSnapshotStatus `json:"status,omitempty"`
}

// +kubebuilder:object:root=true

// InstanceSnapshotList contains a list of InstanceSnapshot.
type InstanceSnapshotList struct {
	metav1.TypeMeta `json:",inline"`
	metav1.ListMeta `json:"metadata,omitempty"`
	Items           []InstanceSnapshot `json:"items"`
}

func init() {
	SchemeBuilder.Register(&InstanceSnapshot{}, &InstanceSnapshotList{})
}
