// workloadClusterClientTimeout bounds the requests performed towards the API server of the workload clusters,
// to prevent an unresponsive control plane from blocking the reconciliation.
const workloadClusterClientTimeout = 10 * time.Second

// WorkloadClusterClientBuilder builds a client to interact with the API server of a workload cluster.
type WorkloadClusterClientBuilder func(cfg *rest.Config) (client.Client, error)

func defaultWorkloadClusterClientBuilder(cfg *rest.Config) (client.Client, error) {
	return client.New(cfg, client.Options{})
}

// enforceClusterAPIServerExposure exposes the API server of the workload cluster through the Gateway,
// and grants cluster-admin permissions to the tenant and to the managers of the template workspace.
func (r *InstanceReconciler) enforceClusterAPIServerExposure(ctx context.Context, names *forge.ClusterResourceNames, cluster *unstructured.Unstructured) error {
	log := ctrl.LoggerFrom(ctx)
	instance := clctx.InstanceFrom(ctx)
	envIndex := clctx.EnvironmentIndexFrom(ctx)
	envStatus := &instance.Status.Environments[envIndex]

	envStatus.ExpositionAccepted = false
	envStatus.APIServerURL = ""

	if !r.ExpositionConfig.GatewayAPIMode || !r.ClusterAPIServerOpts.Enabled() {
		log.V(utils.LogDebugLevel).Info("cluster API server exposure disabled: requires Gateway API mode and OIDC configuration")
		return nil
	}

	ca, err := r.retrieveClusterCA(ctx, names)
	if err != nil || ca == nil {
		return err
	}

	if err := r.enforceClusterAPIServerCAConfigMap(ctx, names, ca); err != nil {
		return err
	}
	if err := r.enforceClusterAPIServerBackendTLSPolicy(ctx, names); err != nil {
		return err
	}
	path := forge.ClusterAPIServerPath(r.ClusterAPIServerOpts.PathPrefix, instance.Namespace, names.Cluster)
	route, err := r.enforceClusterAPIServerHTTPRoute(ctx, names, path)
	if err != nil {
		return err
	}

	// The workload cluster API server is reachable only once the control plane has been initialized.
	if initialized, _, _ := unstructured.NestedBool(cluster.Object, "status", "initialization", "controlPlaneInitialized"); !initialized {
		log.V(utils.LogDebugLevel).Info("waiting for the workload cluster control plane to be initialized", "cluster", names.Cluster)
		return nil
	}

	if err := r.enforceClusterAdmins(ctx, names); err != nil {
		return err
	}

	accepted, err := r.getHTTPRouteAcceptedStatus(ctx, route)
	if err != nil {
		log.Error(err, "failed to read httproute status", "httproute", klog.KObj(route))
		return err
	}
	if !accepted {
		log.Info("httproute not yet accepted by the gateway", "httproute", klog.KObj(route))
		return nil
	}

	envStatus.ExpositionAccepted = true
	envStatus.APIServerURL = forge.ClusterAPIServerURL(r.ExpositionConfig.WebsiteBaseURL, path)
	return nil
}

// retrieveClusterCA returns the PEM-encoded CA certificate of the workload cluster generated by Kamaji,
// or nil if not yet available.
func (r *InstanceReconciler) retrieveClusterCA(ctx context.Context, names *forge.ClusterResourceNames) ([]byte, error) {
	log := ctrl.LoggerFrom(ctx)
	instance := clctx.InstanceFrom(ctx)

	key := types.NamespacedName{Namespace: instance.Namespace, Name: forge.ClusterAPIServerCASecretName(names.ControlPlane)}
	var secret corev1.Secret
	if err := r.Get(ctx, key, &secret); err != nil {
		if kerrors.IsNotFound(err) {
			log.V(utils.LogDebugLevel).Info("waiting for the workload cluster CA to be generated", "secret", key)
			return nil, nil
		}
		log.Error(err, "failed retrieving the workload cluster CA", "secret", key)
		return nil, err
	}

	ca := secret.Data[forge.ClusterAPIServerCAKey]
	if err := validateCertificate(ca); err != nil {
		log.Error(err, "invalid workload cluster CA", "secret", key)
		return nil, err
	}
	return ca, nil
}

func validateCertificate(data []byte) error {
	block, _ := pem.Decode(data)
	if block == nil || block.Type != "CERTIFICATE" {
		return errors.New("no PEM-encoded certificate found")
	}
	_, err := x509.ParseCertificate(block.Bytes)
	return err
}

// enforceClusterAPIServerCAConfigMap copies the workload cluster CA in a ConfigMap, to be referenced by the BackendTLSPolicy.
func (r *InstanceReconciler) enforceClusterAPIServerCAConfigMap(ctx context.Context, names *forge.ClusterResourceNames, ca []byte) error {
	log := ctrl.LoggerFrom(ctx)
	instance := clctx.InstanceFrom(ctx)
	environment := clctx.EnvironmentFrom(ctx)

	configMap := corev1.ConfigMap{}
	configMap.SetName(forge.ClusterAPIServerExposureName(names.Cluster))
	configMap.SetNamespace(instance.Namespace)
	res, err := ctrl.CreateOrUpdate(ctx, r.Client, &configMap, func() error {
		configMap.Data = map[string]string{forge.ClusterAPIServerCAKey: string(ca)}
		configMap.SetLabels(forge.EnvironmentObjectLabels(configMap.GetLabels(), instance, environment))
		return ctrl.SetControllerReference(instance, &configMap, r.Scheme)
	})
	if err != nil {
		log.Error(err, "failed to enforce object", "configmap", klog.KObj(&configMap))
		return err
	}
	log.V(utils.FromResult(res)).Info("object enforced", "configmap", klog.KObj(&configMap), "result", res)
	return nil
}

// enforceClusterAPIServerBackendTLSPolicy configures the Gateway to reach the API server through TLS.
func (r *InstanceReconciler) enforceClusterAPIServerBackendTLSPolicy(ctx context.Context, names *forge.ClusterResourceNames) error {
	log := ctrl.LoggerFrom(ctx)
	instance := clctx.InstanceFrom(ctx)
	environment := clctx.EnvironmentFrom(ctx)

	policy := gatewayv1.BackendTLSPolicy{}
	policy.SetName(forge.ClusterAPIServerExposureName(names.Cluster))
	policy.SetNamespace(instance.Namespace)
	res, err := ctrl.CreateOrUpdate(ctx, r.Client, &policy, func() error {
		policy.Spec = forge.ClusterAPIServerBackendTLSPolicySpec(names.ControlPlane, instance.Namespace, forge.ClusterAPIServerExposureName(names.Cluster))
		policy.SetLabels(forge.EnvironmentObjectLabels(policy.GetLabels(), instance, environment))
		return ctrl.SetControllerReference(instance, &policy, r.Scheme)
	})
	if err != nil {
		log.Error(err, "failed to enforce object", "backendtlspolicy", klog.KObj(&policy))
		return err
	}
	log.V(utils.FromResult(res)).Info("object enforced", "backendtlspolicy", klog.KObj(&policy), "result", res)
	return nil
}

// enforceClusterAPIServerHTTPRoute exposes the API server through the Gateway at the given path.
func (r *InstanceReconciler) enforceClusterAPIServerHTTPRoute(ctx context.Context, names *forge.ClusterResourceNames, path string) (*gatewayv1.HTTPRoute, error) {
	log := ctrl.LoggerFrom(ctx)
	instance := clctx.InstanceFrom(ctx)
	environment := clctx.EnvironmentFrom(ctx)

	route := gatewayv1.HTTPRoute{}
	route.SetName(forge.ClusterAPIServerExposureName(names.Cluster))
	route.SetNamespace(instance.Namespace)
	res, err := ctrl.CreateOrUpdate(ctx, r.Client, &route, func() error {
		// As for the environment routes, the spec is enforced only at creation time or when the Gateway
		// changes, to prevent fighting with the defaults set by the API server.
		if route.CreationTimestamp.IsZero() || r.gatewayDiffers(&route) {
			route.Spec = forge.ClusterAPIServerHTTPRouteSpec(path, names.ControlPlane, &r.ExpositionConfig)
		}
		route.SetLabels(forge.EnvironmentObjectLabels(route.GetLabels(), instance, environment))
		return ctrl.SetControllerReference(instance, &route, r.Scheme)
	})
	if err != nil {
		log.Error(err, "failed to enforce object", "httproute", klog.KObj(&route))
		return nil, err
	}
	log.V(utils.FromResult(res)).Info("object enforced", "httproute", klog.KObj(&route), "result", res)
	return &route, nil
}

// enforceClusterAdmins grants cluster-admin permissions on the workload cluster to the tenant owning the
// instance and to the managers of the template workspace, identified through the OIDC claims.
func (r *InstanceReconciler) enforceClusterAdmins(ctx context.Context, names *forge.ClusterResourceNames) error {
	log := ctrl.LoggerFrom(ctx)
	instance := clctx.InstanceFrom(ctx)
	template := clctx.TemplateFrom(ctx)

	wlClient, err := r.workloadClusterClient(ctx, names)
	if err != nil || wlClient == nil {
		return err
	}

	crb := rbacv1.ClusterRoleBinding{}
	crb.SetName(forge.ClusterAdminsClusterRoleBindingName)
	res, err := ctrl.CreateOrUpdate(ctx, wlClient, &crb, func() error {
		crb.SetLabels(forge.ClusterAdminsLabels(crb.GetLabels()))
		crb.Subjects = forge.ClusterAdminsSubjects(instance.Spec.Tenant.Name, template.Spec.WorkspaceRef.Name)
		crb.RoleRef = forge.ClusterAdminsRoleRef()
		return nil
	})
	if err != nil {
		log.Error(err, "failed to enforce object in the workload cluster", "clusterrolebinding", crb.GetName(), "cluster", names.Cluster)
		return err
	}
	log.V(utils.FromResult(res)).Info("object enforced in the workload cluster", "clusterrolebinding", crb.GetName(), "cluster", names.Cluster, "result", res)
	return nil
}

// workloadClusterClient returns a client to interact with the workload cluster with admin permissions,
// or nil if the admin kubeconfig has not yet been generated.
func (r *InstanceReconciler) workloadClusterClient(ctx context.Context, names *forge.ClusterResourceNames) (client.Client, error) {
	log := ctrl.LoggerFrom(ctx)
	instance := clctx.InstanceFrom(ctx)

	key := types.NamespacedName{Namespace: instance.Namespace, Name: forge.ClusterKubeconfigSecretName(names.Cluster)}
	var secret corev1.Secret
	if err := r.Get(ctx, key, &secret); err != nil {
		if kerrors.IsNotFound(err) {
			log.V(utils.LogDebugLevel).Info("waiting for the workload cluster kubeconfig to be generated", "secret", key)
			return nil, nil
		}
		log.Error(err, "failed retrieving the workload cluster kubeconfig", "secret", key)
		return nil, err
	}

	cfg, err := clientcmd.RESTConfigFromKubeConfig(secret.Data[forge.ClusterKubeconfigKey])
	if err != nil {
		return nil, fmt.Errorf("parse workload cluster kubeconfig %s: %w", key, err)
	}
	// Contact the control plane through its Service, whose hostname is part of the API server certificate SANs.
	cfg.Host = forge.ClusterAPIServerInternalURL(names.ControlPlane, instance.Namespace)
	cfg.Timeout = workloadClusterClientTimeout

	builder := r.WorkloadClusterClientBuilder
	if builder == nil {
		builder = defaultWorkloadClusterClientBuilder
	}
	wlClient, err := builder(cfg)
	if err != nil {
		return nil, fmt.Errorf("create workload cluster client for %s: %w", names.Cluster, err)
	}
	return wlClient, nil
}
